async function main() {
  console.log("Syncing real K & S Beauty Centre services...");

  // Delete old services to replace cleanly with official menu
  await prisma.service.deleteMany({});

  for (const s of REAL_KANDS_SERVICES) {
    await prisma.service.create({
      data: {
        title: s.title,
        description: s.description,
        iconName: s.iconName,
        category: s.category,
        duration: s.duration,
        price: s.price,
        imageUrl: s.imageUrl,
        features: s.features,
        displayOrder: s.displayOrder,
        isActive: true,
      },
    });
  }

  console.log(`Successfully synced ${REAL_KANDS_SERVICES.length} services!`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
